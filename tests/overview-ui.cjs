// Overview UI test: node tests/overview-ui.cjs (needs PLAYWRIGHT_MODULE and a vite server at OVERVIEW_TEST_BASE_URL).
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const { openApp, setPrivacy } = require('./helpers/shell.cjs');
const base = process.env.OVERVIEW_TEST_BASE_URL || 'http://127.0.0.1:18731/';
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
  await openApp(page, base, { mock: 'running' });
  await page.getByTestId('overview-page').waitFor();
  assert.ok(await page.getByTestId('ov-core-version').innerText().then((t) => /v?\d/.test(t)));
  assert.ok(await page.getByTestId('ov-needs').locator('a.ov-row').count() > 0, 'needs-action rows');
  assert.match(await page.locator('.ov-provider').first().getAttribute('href'), /#\/quota\?provider=/);
  assert.match(await page.locator('.ov-usage a').getAttribute('href'), /#\/usage/);
  assert.match(await page.locator('.ov-connect a.ov-link').getAttribute('href'), /#\/settings\/access/);
  assert.match(await page.locator('.ov-needs a.ov-row').first().getAttribute('href'), /#\/(quota|providers)\?cred=/);
  const key = await page.getByTestId('ov-key').innerText();
  assert.match(key, /…/);
  await setPrivacy(page, true);
  assert.doesNotMatch(await page.getByTestId('ov-needs').innerText(), /@example\.test/);
  await setPrivacy(page, false);
  await page.getByRole('button', { name: 'Health check' }).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Stop' }).click();
  await page.getByRole('button', { name: 'Start' }).first().waitFor();
  // Core recovery (dev a12d7c8): attempt/limit/delay come from the status payload; Stop cancels recovery.
  await openApp(page, base, { mock: 'running', query: 'mockRecovery=waiting' });
  const recovery = page.getByTestId('ov-recovery');
  await recovery.waitFor();
  assert.equal(await recovery.getAttribute('data-phase'), 'waiting');
  assert.match(await recovery.innerText(), /Attempt 3 of 5/);
  assert.match(await recovery.innerText(), /Next try in 5s/);
  assert.match(await page.locator('.ov-runtime .ec-chip').first().innerText(), /Recovering · 3\/5/);
  assert.match(await page.locator('.ec-core-line').innerText(), /Core recovering · 3\/5/);
  assert.equal(await page.locator('.ec-core-line').getAttribute('data-core-status'), 'recovering');
  await page.getByRole('button', { name: 'Stop recovery' }).click();
  await page.locator('.ov-runtime[data-runtime-state="stopped"]').waitFor();
  assert.equal(await page.getByTestId('ov-recovery').count(), 0);
  assert.equal(await page.locator('.ec-core-line').getAttribute('data-core-status'), 'stopped');
  await openApp(page, base, { mock: 'running', query: 'mockRecovery=failed' });
  await page.locator('[data-testid="ov-recovery"][data-phase="failed"]').waitFor();
  assert.equal(await page.locator('.ov-runtime[data-runtime-state="recoveryFailed"]').count(), 1);
  assert.equal(await page.locator('.ec-core-line').getAttribute('data-core-status'), 'recoveryFailed');
  await page.getByRole('button', { name: 'Start' }).first().click();
  await page.locator('.ov-runtime[data-runtime-state="running"]').waitFor();
  await openApp(page, base, { mock: 'empty' });
  await page.getByTestId('ov-onboarding').waitFor();
  // Guided setup (Easy mode) is reachable from Get started and opens inside the shell.
  await page.getByTestId('ov-onboarding').getByRole('button', { name: 'Guided setup' }).click();
  await page.waitForFunction(() => location.hash === '#/easy');
  await page.locator('.simple-mode-page').waitFor();
  assert.equal(errors.length, 0, errors.join('\n'));
  await browser.close();
  console.log('overview-ui ok');
})().catch((e) => { console.error(e); process.exit(1); });
