const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { launchBrowser } = require('./ui-harness.cjs');
const assert = require('node:assert/strict');
const path = require('node:path');
const { mkdirSync } = require('node:fs');

(async () => {
  const { createServer } = await import('vite');
  const react = (await import('@vitejs/plugin-react')).default;
  const server = await createServer({ configFile: false, root: path.resolve(__dirname, '..'), plugins: [react()],
    logLevel: 'error', server: { host: '127.0.0.1', port: 0, watch: null } });
  let browser;
  try {
    await server.listen();
    const base = `http://127.0.0.1:${server.httpServer.address().port}`;
    browser = await launchBrowser(chromium, { args: ['--no-proxy-server'] });
    const page = await browser.newPage({ viewport: { width: 1505, height: 1000 } });
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    await page.addInitScript(() => localStorage.setItem('easy-cli-proxy-api.locale', 'en'));
    await page.goto(`${base}/?mock=running&mockDelay=5`);
    await page.locator('.app-shell').waitFor();
    await page.locator('.nav-section button').nth(2).click();
    const card = page.locator('.vertex-login-card');
    const opener = card.getByRole('button', { name: 'Import Vertex Credential', exact: true });
    const cardHeight = (await card.boundingBox()).height;
    assert.equal(await card.locator('input').count(), 0);
    await opener.click();
    const dialog = page.getByRole('dialog', { name: 'Import Vertex Credential', exact: true });
    await dialog.waitFor();
    await page.waitForFunction(() => document.activeElement?.textContent === 'Choose file');
    const submit = dialog.getByRole('button', { name: 'Import Vertex Credential', exact: true });
    await submit.click();
    assert.match(await dialog.getByRole('alert').textContent(), /Select a Google/);
    const upload = (text, name = 'service-account.json') => dialog.locator('input[type=file]').setInputFiles({ name, mimeType: 'application/json', buffer: Buffer.from(text) });
    await upload('{broken');
    await submit.click();
    assert.match(await dialog.getByRole('alert').textContent(), /JSON object/);
    await upload('[]');
    await submit.click();
    assert.match(await dialog.getByRole('alert').textContent(), /JSON object/);
    await upload('{}');
    await submit.click();
    await dialog.getByRole('alert').filter({ hasText: 'invalid service account' }).waitFor();
    // Synthetic data for browser mock only, never a real Google credential.
    await upload(JSON.stringify({ project_id: 'vertex-ui-test', client_email: 'test@example.invalid', private_key: 'mock-private-key' }));
    await submit.click();
    await dialog.getByRole('status').waitFor();
    assert.match(await dialog.getByRole('status').textContent(), /us-central1/);
    await dialog.getByLabel('GCP location', { exact: false }).fill('  asia-east1  ');
    await submit.click();
    await dialog.getByRole('status').waitFor();
    assert.match(await dialog.getByRole('status').textContent(), /asia-east1/);
    assert.equal((await card.boundingBox()).height, cardHeight);
    mkdirSync('bin-work', { recursive: true });
    await dialog.screenshot({ path: 'bin-work/vertex-import-dialog.png' });
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await opener.evaluate(element => element === document.activeElement), true);
    await card.screenshot({ path: 'bin-work/vertex-login.png' });
    await page.screenshot({ path: 'bin-work/vertex-login-page.png', fullPage: true });
    await page.setViewportSize({ width: 640, height: 600 });
    await opener.click();
    await dialog.waitFor();
    const bounds = await dialog.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 640 && bounds.y + bounds.height <= 600);
    const first = dialog.getByRole('button', { name: 'Close', exact: true });
    await first.focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await submit.evaluate(element => element === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await first.evaluate(element => element === document.activeElement), true);
    await page.screenshot({ path: 'bin-work/vertex-import-compact.png' });
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 1505, height: 1000 });
    await page.getByRole('tab', { name: 'Authentication Files', exact: true }).click();
    await page.locator('.auth-list-pagination select').selectOption('50');
    const credential = page.locator('.auth-file-card').filter({ has: page.locator('.auth-card-filename[title="vertex-vertex-ui-test.json"]') });
    await credential.waitFor();
    assert.equal(await credential.count(), 1);
    assert.deepEqual(errors, []);
    console.log('PASS: Vertex import dialog, validation, locations, stable card height, focus restoration/trap, compact layout and credential replacement.');
  } finally { await browser?.close(); await server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
