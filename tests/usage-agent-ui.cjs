const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { launchBrowser, runUi } = require('./ui-harness.cjs');
const assert = require('node:assert/strict');
runUi(async ({ base }) => {
  const browser = await launchBrowser(chromium);
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    await page.addInitScript(() => localStorage.clear());
    await page.goto(`${base}/tests/fixtures/usage-layout.html?tab=events&locale=en&theme=light`);
    await page.locator('.usage-td-agent').first().waitFor();
    assert.deepEqual((await page.locator('.usage-td-agent').allTextContents()).slice(0, 4), ['Codex', 'Claude Code', 'Gemini CLI', 'Unknown']);
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    await page.waitForFunction(() => window.usageKeyFixture.eventQueries.at(-1).page === 2);
    await page.getByRole('button', { name: 'Agent', exact: true }).click();
    await page.getByRole('option', { name: 'Claude Code', exact: true }).click();
    await page.waitForFunction(() => {
      const q = window.usageKeyFixture.eventQueries.at(-1);
      return q.agent === 'claude-code' && q.page === 1;
    });
    assert.equal(await page.locator('.usage-td-agent').count(), 50);
    assert.ok((await page.locator('.usage-td-agent').allTextContents()).every(text => text === 'Claude Code'));
    await page.locator('.usage-events-export-btn').click();
    await page.waitForFunction(() => window.usageKeyFixture.exportedCsv.length > 0);
    const exported = await page.evaluate(() => window.usageKeyFixture.exportedCsv);
    const rows = exported.replace(/^\uFEFF/, '').split('\r\n');
    assert.equal(rows.length, 101, 'Export includes all filtered records across UI pages');
    assert.ok(rows[0].includes('"agent"'));
    assert.ok(!rows[0].includes('user_agent'));
    assert.ok(rows.slice(1).every(row => row.includes('"claude-code"')));
    await page.getByRole('button', { name: 'Agent', exact: true }).click();
    await page.getByRole('option', { name: 'Unknown', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.usage-td-agent')?.textContent === 'Unknown');
    assert.ok((await page.locator('.usage-td-agent').allTextContents()).every(text => text === 'Unknown'));
    await page.locator('.usage-col-settings-btn').click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('checkbox', { name: 'Agent', exact: true }).uncheck();
    await dialog.locator('.primary-button').click();
    assert.equal(await page.locator('.usage-th-agent').count(), 0);
    await page.locator('.usage-col-settings-btn').click();
    await page.getByRole('dialog').getByRole('checkbox', { name: 'Agent', exact: true }).check();
    await page.getByRole('dialog').locator('.primary-button').click();
    await page.setViewportSize({ width: 390, height: 850 });
    assert.equal(await page.locator('.usage-th-agent').count(), 1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('PASS: Agent column, server query/filter page reset, unknown, all-filtered CSV, column picker, narrow layout.');
  } finally { await browser.close(); }
}, { url: process.env.PLAYWRIGHT_BASE_URL });
